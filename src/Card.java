/**
 * Represents a card with a name and two attack strings.
 */
public class Card {

    private String name;
    private String attackOneStr;
    private String attackTwoStr;

    /**
     * Returns the name associated with this object.
     *
     * @return The name of the object
     */
    public String getName() {
        return name;
    }


    /**
     * Retrieves the description of the first attack.
     *
     * @return The description of the first attack.
     */
    public String getAttackOne() { return attackOneStr; }
    /**
     * Returns the attack two string.
     *
     * @return The attack two string.
     */
    public String getAttackTwo() { return attackOneStr; }

}
